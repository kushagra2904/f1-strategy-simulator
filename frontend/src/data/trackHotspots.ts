// Interactive overlay hotspots for circuit maps. Coordinates are normalized
// (0–1) relative to the track image, so they scale with the rendered <img>.
// They sit on top of the annotations already baked into the AVIF maps (corner
// numbers, DRS zones, speed trap, sectors) to make them hoverable/clickable.
//
// Keyed by the track's image file name (matches Track.file from the backend).
// Tracks without an entry simply render the plain image.

export type HotspotType =
  | "corner"
  | "drs"
  | "speed-trap"
  | "sector"
  | "start";

export interface Hotspot {
  id: string;
  /** normalized center, 0–1 */
  x: number;
  y: number;
  type: HotspotType;
  label: string;
  detail?: string;
}

